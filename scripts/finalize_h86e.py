#!/usr/bin/env python3
"""Finalize the H86E lane: emit the final candidate GeoTIFF from the cached
full-catalogue model surface, validate it with the shared validator, measure
like-for-like registry uniqueness with the shared two-phase summary, apply the
automated gates, and write the run card.  No human inspection step: every gate
is computed here and the verdict is whatever the gates return.

Gate definitions (all must pass for a promote-to-selector verdict):
  G1 format      shared gems57.validate all_checks_passed (single band,
                 float32, EPSG:32611, shape/transform pinned, all-finite,
                 values in [0,1], zero outside footprint and on catalogue)
  G2 canary      max single-feature discriminative AUC < 0.90 (from run_h86e)
  G3 holdout     pooled HOLDOUT-DTI of the OOF pipeline arm exceeds the best
                 honest control (spaced random / distance-only / SPBT) ...
  G4 holdout-best ... and exceeds the best previously recorded value on the
                 *identical* instrument (buffered whole components, seed 20,
                 gems57-pooled-hide-v2, same budget): H86C-KSLB E3.
  G5 SGMC proxy  auxiliary off-catalogue proxy DTI exceeds spaced random and
                 the h33-h33-2-b2 fixed-raster reading (never a score).
  G6 uniqueness  like-for-like reading of the shared two-phase summary over
                 every local registry raster: worst dot-field 3 px overlap
                 <= 0.70 and worst |Spearman| <= 0.90 (surfaces and final
                 dots).  The literal reading is also reported; the pinned
                 full-support dense witness and the stride-5 lattice are
                 known degenerate literal blockers (see
                 docs/evidence/protocol-preflight.json) and are reported,
                 not silently dropped.
"""
from __future__ import annotations

import hashlib
import json
import sys
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import rasterio
from scipy import ndimage as ndi

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "vendor"))
sys.path.insert(0, str(ROOT))

from gems57 import grid as G  # noqa: E402
from gems57 import emit as E  # noqa: E402
from gems57 import metric as M  # noqa: E402
from gems57 import validate as V  # noqa: E402
from gems57.uniqueness import dot_overlap, surface_rho, two_phase_summary, _dots  # noqa: E402

CACHE = ROOT / ".cache" / "h86e"
BUDGET = 44090


def sha256(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def loadmask(p: Path) -> np.ndarray:
    with rasterio.open(p) as s:
        a = s.read(1)
    return a


def main():
    t0 = time.time()
    g = G.load_grid()
    fp, cat = g.footprint, g.catalogue
    results = json.loads((CACHE / "h86e_results.json").read_text())

    # ---------- emit final candidate ----------
    surf = np.load(CACHE / "final_surface.npy")
    surf = np.sqrt(np.clip(surf, 0, 1)).astype(np.float32)
    surf[~fp] = 0.0
    dcat = ndi.distance_transform_edt(~cat)
    allowed = fp & (dcat > 2.0)
    ranked, _ = E.emit_decimated(surf, allowed, tile_px=3)
    dots = E.emit_prefix(ranked, BUDGET)
    pred = dots.astype(np.float32)

    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    digest8 = hashlib.sha256(pred.tobytes()).hexdigest()[:8]
    stem = f"gems86-h86e-cctx-{BUDGET}dots-{ts}-{digest8}-zeros"
    tif = ROOT / "docs/downloads" / f"{stem}.tif"
    G.write_submission(tif, pred, mode="zeros")
    val = V.validate(tif, fp, cat)
    V.assert_submittable(val)

    zip_path = tif.with_suffix(".zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(tif, tif.name)

    hold = results["e3_pooled"]["scores"][f"cctv_oof_{BUDGET}"]
    name = f"gems86-h86e-cctx-{BUDGET}dots-{ts}-{digest8}"
    note = (f"H86E-CCTX cat-context LOQO-HGB+SPBTchan {BUDGET}dots B2 HOLDOUT-DTI "
            f"{hold['dti']:.4f} v2 n=11321 UNSCORED")[:140]
    receipt = dict(
        file=tif.name, sha256=sha256(tif), bytes=tif.stat().st_size,
        submission_name=name, note=note, note_chars=len(note),
        validator=val,
        zip_file=zip_path.name, zip_sha256=sha256(zip_path),
        approved_for_weekly_slot=False, promoted=False, submission_slots_used=0,
        status="generated by scripts/finalize_h86e.py; automated gates in docs/evidence/h86e-run-card.json decide submission eligibility",
        metadata=dict(lane="H86E-CCTX", winner_arm=f"cctv_oof_{BUDGET}", budget=BUDGET,
                      content_digest8=digest8),
    )
    tif.with_suffix(".json").write_text(json.dumps(receipt, indent=1) + "\n")
    print("wrote", tif.name, receipt["sha256"][:12], "dots", int(dots.sum()), flush=True)

    # ---------- SGMC auxiliary proxy for the final file ----------
    with rasterio.open(ROOT / "data/external/derived_sgmc_faults_100m_u8.tif") as s:
        sgmc = s.read(1) > 0
    truth_sg = sgmc & fp & ~cat
    sg_final = M.dti_exact(pred, truth_sg, valid=fp, known=cat)
    sg = results["sgmc_auxiliary_proxy"]

    # ---------- uniqueness (shared two-phase summary over local registry) ----------
    reg_paths = sorted((ROOT / "data/scored_fleet").glob("*.tif"))
    reg_paths += sorted((ROOT / "data/scored").glob("*.tif"))
    reg_paths += [p for p in sorted((ROOT / "docs/downloads").glob("*.tif")) if p != tif]
    dense_witness = ROOT / "data/registry/dense-witness.tif"
    if dense_witness.exists():
        reg_paths.append(dense_witness)
    seen, rows, surf_rows = {}, [], []
    my_dots = _dots(pred)
    for p in reg_paths:
        h = sha256(p)
        if h in seen:
            continue
        seen[h] = p.name
        a = loadmask(p)
        if a.shape != pred.shape:
            continue
        their = np.where(fp, np.nan_to_num(a.astype(np.float32), nan=0.0), 0.0)
        td = _dots(their)
        rho_surf = surface_rho(surf, their, fp)
        rho_dot = surface_rho(pred, their, fp)
        rows.append(dict(
            submission=p.name, repo=str(p.parent.relative_to(ROOT)), sha256=h,
            their_dots=int((td & fp).sum()),
            my_dots_within_3px_of_theirs=dot_overlap(pred, their),
            their_dots_within_3px_of_mine=dot_overlap(their, pred),
            jaccard_dot_sets=rho_dot["jaccard_dot_sets"],
            spearman_full_footprint=rho_dot["spearman_full_footprint"],
        ))
        surf_rows.append(dict(submission=p.name,
                              spearman_full_footprint=rho_surf["spearman_full_footprint"],
                              spearman_on_dot_union=rho_surf["spearman_on_dot_union"]))
    uniq = two_phase_summary(rows, int(fp.sum()), expected_rasters=len(rows))
    worst_surf_rho = max((abs(r["spearman_full_footprint"]) for r in surf_rows
                          if r["spearman_full_footprint"] is not None and np.isfinite(r["spearman_full_footprint"])),
                         default=None)
    (ROOT / "docs/evidence/h86e_uniqueness.json").write_text(json.dumps(
        dict(rows=rows, surface_rows=surf_rows, summary=uniq,
             candidate_file=str(tif.relative_to(ROOT)), candidate_sha256=receipt["sha256"],
             worst_abs_surface_spearman=worst_surf_rho,
             registry_scope=f"{len(rows)} unique local rasters (scored fleet + ancestors + prior lane downloads + dense witness); not an organizer-complete registry"),
        indent=1) + "\n")
    print("uniqueness like-for-like worst dot overlap:",
          uniq["like_for_like_reading"]["worst_forward_overlap_dot_fields"],
          "literal worst:", uniq["literal_reading"]["worst_forward_overlap"], flush=True)

    # ---------- gates ----------
    kslb = json.loads((ROOT / "docs/evidence/lane86c_results.json").read_text())
    hold_best = kslb["holdout_buffered_whole_components"]["scores"]["E3_kslb_noisyor_44k"]
    controls = {k: results["e3_pooled"]["scores"][k]["dti"]
                for k in ("spaced_random", "neg_dist_visible", "conc_unweighted")}
    best_control = max(controls, key=controls.get)
    delta_vs_control = results["e3_pooled"]["paired_differences"][best_control]
    like = uniq["like_for_like_reading"]
    gates = dict(
        G1_format=dict(passed=bool(val["all_checks_passed"]), checks=val["checks"]),
        G2_canary=dict(passed=bool(results["canary_max_discriminative"] < 0.90),
                       max_discriminative_auc=results["canary_max_discriminative"], limit=0.90),
        G3_holdout_vs_controls=dict(
            passed=bool(hold["dti"] > controls[best_control] and delta_vs_control["ci95"][0] > 0),
            candidate=hold["dti"], best_control=best_control, best_control_dti=controls[best_control],
            paired_delta=delta_vs_control["delta"], paired_delta_ci95=delta_vs_control["ci95"]),
        G4_holdout_best=dict(
            passed=bool(hold["dti"] > hold_best["dti"]),
            candidate=hold["dti"], candidate_ci95=hold["ci95"],
            current_best="H86C-KSLB E3_kslb_noisyor_44k (docs/evidence/lane86c_results.json, identical instrument)",
            current_best_dti=hold_best["dti"], current_best_ci95=hold_best["ci95"]),
        G5_sgmc_proxy=dict(
            passed=bool(sg_final["dti"] > sg["spaced_random"]["dti"] and sg_final["dti"] > sg["fixed_h33_b2"]["dti"]),
            candidate_final_file=sg_final["dti"], spaced_random=sg["spaced_random"]["dti"],
            fixed_h33_b2=sg["fixed_h33_b2"]["dti"],
            note="AUXILIARY-PROXY only; never a score. SGMC shares lineage with the catalogue and rewards near-catalogue placement."),
        G6_uniqueness=dict(
            passed=bool(like["worst_forward_overlap_dot_fields"] <= 0.70
                        and (uniq["literal_reading"]["worst_spearman_full_footprint"] or 0) <= 0.90
                        and (worst_surf_rho or 0) <= 0.90),
            worst_dot_field_overlap=like["worst_forward_overlap_dot_fields"],
            worst_dot_field_submission=like["worst_forward_overlap_dot_field_submission"],
            worst_abs_surface_spearman=worst_surf_rho,
            literal_worst_overlap=uniq["literal_reading"]["worst_forward_overlap"],
            literal_worst_submission=uniq["literal_reading"]["worst_overlap_submission"],
            literal_note="Literal reading fires on the pinned full-support dense witness / stride-5 lattice for every nonempty candidate; reported via the shared two-phase summary, thresholds unchanged."),
    )
    promote = all(g["passed"] for g in gates.values())
    verdict = "promote-to-selector-only" if promote else "negative"
    failed = [k for k, g in gates.items() if not g["passed"]]

    card = dict(
        schema="gems86.h86e-run-card.v1",
        lane="H86E (SPBT E1-E2; CCTX E3)",
        generated_utc=datetime.now(timezone.utc).isoformat(),
        hypothesis=("Expert-mapped new faults are recoverable from (a) signed paired-throw "
                    "basement/gravity concordance under low-relief cover (SPBT, E1-E2) and "
                    "(b) visible-catalogue context + label-free geophysics learned LOQO (CCTX, E3)."),
        mechanism=("SPBT: depth-to-basement flank step anti-concordant with isostatic-gravity "
                   "flank step, >=900 m strike continuity. CCTX: LOQO HistGradientBoosting over "
                   "19 competition bands + gradients + LiDAR/topo/radiometrics + SPBT channel + "
                   "other-component catalogue distance/density context; 300 m decimated emission at "
                   f"{BUDGET} dots, >2 px off catalogue."),
        named_non_fault_process=("SPBT mimic: unfaulted paleovalley/caldera-moat margins infilled by "
                                 "low-density sediment. CCTX mimic: lithologic contacts and the mapped-"
                                 "network halo (fault-parallel contacts near range fronts)."),
        holdout_dti=dict(evidence_class="HOLDOUT-DTI", evaluator_version="gems57-pooled-hide-v2",
                         design="buffered whole components, seed 20, LOQO, 20 km physical-block bootstrap",
                         withheld_positives=int(hold["withheld_positive_pixels"]),
                         value=hold["dti"], ci95=hold["ci95"]),
        # keys consumed by scripts/audit_release.py archived_holdout(kind="pooled")
        holdout_source="docs/evidence/h86e_results.json",
        correlation_overlap_vs_registry=dict(
            worst_abs_surface_spearman=worst_surf_rho,
            worst_dot_field_overlap=like["worst_forward_overlap_dot_fields"],
            worst_dot_field_submission=like["worst_forward_overlap_dot_field_submission"],
            literal_worst_overlap=uniq["literal_reading"]["worst_forward_overlap"],
            rasters_checked=len(rows), evidence="docs/evidence/h86e_uniqueness.json"),
        raster_sha256=receipt["sha256"],
        validator_output=dict(all_checks_passed=val["all_checks_passed"],
                              n_nan_inside_footprint=int(np.isnan(pred[fp]).sum()),
                              min=val["min"], max=val["max"], checks=val["checks"],
                              emitted_dots=int(dots.sum())),
        gates=gates, gates_failed=failed,
        submission_name=name, note=note, note_chars=len(note),
        submission_file=str(tif.relative_to(ROOT)),
        verdict="negative" if not promote else "promote",
        submission_ready=False, safe_to_submit=False, approved_for_weekly_slot=False,
        decision="OK TO SUBMIT (selector step still required)" if promote else "DO NOT SUBMIT",
        decision_reason=("All automated gates passed." if promote else
                         f"Automated gates failed: {', '.join(failed)}. Generated and format-valid, but not cleared for a weekly slot."),
        experiments_run=3, submission_slots_used=0,
        elapsed_s=float(time.time() - t0),
    )
    # archived_holdout(kind="pooled") reads card["holdout_dti"] with caller-side
    # schema {evidence_class, evaluator_version, withheld_positives, value, ci95} - match it.
    (ROOT / "docs/evidence/h86e-run-card.json").write_text(json.dumps(card, indent=1) + "\n")
    (ROOT / "docs/evidence/h86e_results.json").write_text(
        (CACHE / "h86e_results.json").read_text())
    print("VERDICT:", card["decision"], "| failed:", failed, flush=True)
    print(json.dumps({k: v.get("passed") for k, v in gates.items()}, indent=1))


if __name__ == "__main__":
    main()
